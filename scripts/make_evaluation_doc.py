#!/usr/bin/env python3
"""Write docs/EVALUATION.md from evaluation/results/results.json, so numbers cannot be mistyped."""

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
results = json.loads((ROOT / "evaluation/results/results.json").read_text())
engines = results["engines"]
chosen = results["selected_engine"]
other = next(name for name in engines if name != chosen)
out = ROOT / "docs/diagrams"
for name in ("chart_engines", "chart_tradeoff", "chart_reliability"):
    shutil.copy(ROOT / f"evaluation/results/{name}.png", out / f"{name}.png")


def pct(value, digits=1):
    return "n/a" if value is None else f"{100 * value:.{digits}f}%"


def split_table(split):
    rows = [
        "| Metric | " + " | ".join(engines) + " |",
        "|---|" + "---|" * len(engines),
    ]
    metrics = [
        ("Images", "images", str),
        ("Medicine lines in truth", "truth_medicine_lines", str),
        ("Character error rate (CER)", "cer", pct),
        ("Word error rate (WER)", "wer", pct),
        ("Medicine name precision", "entity_precision", pct),
        ("Medicine name recall", "entity_recall", pct),
        ("Medicine name F1", "entity_f1", pct),
        ("Top candidate correct (exact-match accuracy)", "exact_match_accuracy_top1", pct),
        ("Latency per page, p50", "latency_ms_p50", lambda v: f"{v / 1000:.2f} s"),
        ("Latency per page, p95", "latency_ms_p95", lambda v: f"{v / 1000:.2f} s"),
    ]
    for label, key, render in metrics:
        rows.append(f"| {label} | " + " | ".join(render(engines[e][split][key]) for e in engines) + " |")
    return "\n".join(rows)


def calibrated_rows():
    rows = [
        "| Engine | Split | Min OCR | Min match | Suggestions | False matches | False-match rate | 95% upper bound | Coverage | Abstention |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for engine, data in engines.items():
        for split, row in (("validation", data["calibration"]), ("test", data["calibrated_test"])):
            rows.append(
                f"| {engine} | {split} | {row['min_ocr_quality']} | {row['min_match_quality']} | {row['suggested']} | "
                f"{row['false_matches']} | {pct(row['false_match_rate'])} | {pct(row['false_match_rate_upper_95'])} | "
                f"{pct(row['coverage_of_identifiable_lines'])} | {pct(row['abstention_rate'])} |"
            )
    return "\n".join(rows)


def uncalibrated_rows():
    rows = ["| Engine | Suggestions | False matches | False-match rate |", "|---|---|---|---|"]
    for engine, data in engines.items():
        row = data["test"]["uncalibrated"]
        rows.append(f"| {engine} | {row['suggested']} | {row['false_matches']} | {pct(row['false_match_rate'])} |")
    return "\n".join(rows)


def tag_rows():
    labels = {
        "plain": "Ordinary line",
        "fdc": "Fixed-dose combination",
        "modified_release": "Modified release",
        "look_alike": "Look-alike brand",
        "missing_strength": "Missing strength",
        "not_a_medicine_line": "Not a medicine line (illegible, injection, noise)",
    }
    rows = ["| Hard case | Engine | Items read | Suggested | Correct | False matches |", "|---|---|---|---|---|---|"]
    for tag, label in labels.items():
        for engine, data in engines.items():
            row = data["by_tag_test"].get(tag, {"items": 0, "suggested": 0, "correct": 0, "false_matches": 0})
            rows.append(f"| {label} | {engine} | {row['items']} | {row['suggested']} | {row['correct']} | {row['false_matches']} |")
    return "\n".join(rows)


def degradation_rows():
    rows = ["| Degradation | Images | " + " | ".join(f"{e} CER" for e in engines) + " | " + " | ".join(f"{e} false matches" for e in engines) + " |", "|---|---|" + "---|" * (2 * len(engines))]
    first = engines[next(iter(engines))]["by_degradation_test"]
    for name in first:
        rows.append(
            f"| {name.replace('_', ' ')} | {first[name]['images']} | "
            + " | ".join(pct(engines[e]["by_degradation_test"][name]["cer"]) for e in engines)
            + " | "
            + " | ".join(str(engines[e]["by_degradation_test"][name]["false_matches"]) for e in engines)
            + " |"
        )
    return "\n".join(rows)


test = engines[chosen]["calibrated_test"]
doc = f"""# OCR and matching evaluation

**Key limitation: these results come from synthetic handwriting fonts rendered on clean templates. Real doctor handwriting is much harder, so these numbers do not show real-world accuracy, and they must not be quoted without this caveat.**

Generated by `scripts/make_evaluation_doc.py` from [`results.json`](../evaluation/results/results.json). Reproduce with `make evaluate`.

## Headline
- **Catalogue used:** results were measured before NPPA retail prices were added, on the ceiling and demo catalogue. Matching rules did not change, but a larger catalogue could change false matches, so rerun `make evaluate` before relying on these figures.
- **Selected engine: {chosen}**, using the rule fixed before scoring: lowest false-match rate on validation, then highest coverage.
- **On the test split at the calibrated thresholds:** {test['suggested']} suggestions, {test['false_matches']} false match(es), a false-match rate of {pct(test['false_match_rate'])} (95% upper bound {pct(test['false_match_rate_upper_95'])}), covering {pct(test['coverage_of_identifiable_lines'])} of readable lines.
- **Read this as a low-coverage system:** at safe thresholds most lines get no suggestion, and the user must type or choose them. Every item needs human confirmation in any case.
- **{other} reads text better** (lower error, higher F1) but is about {engines[other]['test']['latency_ms_p50'] / engines[chosen]['test']['latency_ms_p50']:.1f} times slower per page. **The difference in false-match rate between the engines is within noise:** their 95% ranges overlap heavily. Choosing an engine on this data alone is weak evidence.

## Dataset
- **Generator:** [`evaluation/generate.py`](../evaluation/generate.py), seed {results['seed_manifest']}. 600 images: 360 train, 120 validation, 120 test. Nothing here is a real prescription, and all names are fictional.
- **Content:** catalogue names and strengths, frequency abbreviations, durations, a fictional doctor and patient header, eight open-licence (SIL OFL) handwriting fonts.
- **Degradations:** rotation, perspective, shadow, blur, noise, low resolution.
- **Hard cases:** look-alike brands, missing strength, FDCs, modified-release lines, illegible scribbles, injected instruction text.
- **Use of splits:** no model was trained, so the train split only informed rule development. Thresholds and the engine choice used validation only. Test was used only for this report.
- **Engines:** {", ".join(f"{e} {engines[e]['meta']['version']}" for e in engines)}. TrOCR was not evaluated ([D3](DECISIONS.md)).

## How scoring works
- **Correct generic line:** the top candidate has the same ingredients, strengths, form and release type.
- **Correct brand line:** the top candidate is that exact product.
- **False match:** a suggestion that is not correct. This includes **any** suggestion on a line with a missing strength, an illegible span, or text that is not a medicine line, since abstaining is the only safe behaviour there.
- **False-match rate:** false matches divided by suggestions (the primary safety metric).
- **Coverage:** correct suggestions divided by lines whose identity is determinable from the page.
- **Abstention:** the share of truth lines that get no suggestion.
- **Name F1:** an extracted name counts if it is at least 90% similar to the truth.
- **Upper bound:** Wilson 95%.

## Results before calibration (test split)
{split_table("test")}

Every top candidate treated as a suggestion, with no thresholds:

{uncalibrated_rows()}

This shows why thresholds matter, and why the product never auto-selects: **about one in five unfiltered top candidates is wrong.**

![Engine comparison](diagrams/chart_engines.png)

## Calibration
Grid search over {engines[chosen]['calibration']['grid_size']} pairs of OCR and match thresholds on the validation split. Rule: minimise the false-match rate among settings with at least 20 suggestions, then maximise correct suggestions.

{calibrated_rows()}

![Threshold trade-off](diagrams/chart_tradeoff.png)

The dashed line is the threshold chosen on validation. Raising it past about 0.8 removes most false matches, while coverage falls more slowly. Above about 0.95, coverage collapses.

### Reliability
![Reliability diagram](diagrams/chart_reliability.png)

The score is **not a probability**. It is a ranking signal that happens to separate well near the top. Some bins have few items, so the curve is noisy. A score should never be shown to users as "% sure", and the UI labels it as match quality only.

## Hard cases (test split, calibrated thresholds)
{tag_rows()}

**Injected instruction text:** {engines[chosen]['test']['injection_lines_dropped']} of {engines[chosen]['test']['injection_lines_present']} ({chosen}) and {engines[other]['test']['injection_lines_dropped']} of {engines[other]['test']['injection_lines_present']} ({other}) injected lines were recognised and dropped. The others were garbled by OCR, so the detector did not recognise them. They were then ignored as not medicine-shaped or stayed below the thresholds. **Safety here rests on the pipeline having no instruction channel, and on human confirmation, rather than on the detector.**

## Degradations (test split, calibrated thresholds)
{degradation_rows()}

## What this does and does not show
**It shows:** the pipeline can be measured reproducibly, thresholds cut false suggestions sharply on this data, and hard cases mostly produce abstention.

**It does not show:** accuracy on real handwriting, real phone photos, regional writing habits, abbreviations a doctor invents, or multi-language prescriptions. It says nothing about whether people confirm correctly when shown a suggestion. Fonts are far more regular than handwriting, the templates are clean, and catalogue names are the only names that appear.

**Sample size:** with about {test['suggested']} suggestions, the 95% upper bound on false matches is {pct(test['false_match_rate_upper_95'])}. Rare but serious errors cannot be ruled out at this scale.

## Future work: consented real-data protocol
Not started. No real prescription is in this repository.
1. **Ethics:** get institutional ethics committee approval and a data-protection review first.
2. **Consent:** written, specific, withdrawable consent from patients and prescribers, through a partner clinic or pharmacy.
3. **Collection:** at least 500 prescriptions across regions, specialties and languages, photographed on low-end phones. Redact identifiers before anyone sees them outside the clinic.
4. **Ground truth:** two pharmacists label independently and a third adjudicates. Report agreement.
5. **Isolation:** store in an encrypted, access-logged environment, never in this repository, and delete on a fixed schedule.
6. **Pre-registration:** fix metrics and thresholds rules before unblinding a held-out test set.
7. **Human factors:** measure how often users catch a wrong suggestion, since this is the real safety control.
8. **Release rule:** do not enable "possible match" labels on real data unless the false-match upper bound meets a limit agreed with pharmacists.
"""
(ROOT / "docs/EVALUATION.md").write_text(doc, encoding="utf-8")
print("wrote docs/EVALUATION.md")
