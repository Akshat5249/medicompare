#!/usr/bin/env python3
"""Build VERIFICATION_REPORT.md from verification/gate_status.tsv and captured logs only.

A gate with no status row is NOT EXECUTED. A PASS without a log file is downgraded to FAIL.
"""

from __future__ import annotations

import json
import platform
import re
import subprocess
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOGS = ROOT / "verification/logs"
GATES = {
    "build_stack": "Docker images build; stack healthy",
    "seed_demo_users": "Local demo accounts created",
    "lint": "Ruff, ESLint, Prettier: zero errors",
    "types": "mypy (strict on core), tsc --noEmit",
    "backend_tests": "pytest; coverage at least 85% overall, 95% on safety, matching, pricing",
    "safety_suite": "Safety invariant suite: 100% pass",
    "frontend_tests": "Vitest; coverage at least 80%",
    "smoke": "Smoke tests against the running stack",
    "data_quality": "Data-quality checks on seeded data",
    "e2e_accessibility": "Playwright desktop and mobile with video; axe: no serious or critical",
    "demo_media": "Playwright videos and README GIF collected",
    "performance": "Load test results recorded",
    "backup_restore": "Backup and restore into a scratch database",
    "security": "Bandit, pip-audit, npm audit, Trivy, Gitleaks",
    "zap_baseline": "OWASP ZAP baseline",
    "prod_config": "Production Compose file validates (syntax only)",
    "docs": "Mermaid renders, OpenAPI validates and matches code, links resolve",
}
NOT_RUNNABLE = {
    "Production deployment": ("No server, domain or hosting account is available.", "Follow docs/DEPLOYMENT.md."),
    "HTTPS through Caddy": ("Needs a public domain.", "docker compose -f docker-compose.yml -f docker-compose.prod.yml up -d"),
    "ClamAV in the running stack": (
        "ClamAV runs only in the production profile and needs about 1.5 GB. The hook is unit-tested with a fake socket.",
        "Start the production profile and upload the EICAR test file.",
    ),
    "Optional LLM adapter against the live API": (
        "No API key is used, and the adapter is off by default. Tested with a fake client.",
        "Set LLM_API_KEY and call extract_with_llm on synthetic text.",
    ),
}


def version(*command: str) -> str:
    try:
        return subprocess.run(command, capture_output=True, text=True, timeout=30).stdout.strip().splitlines()[0]  # noqa: S603
    except (OSError, IndexError, subprocess.TimeoutExpired):
        return "unavailable"


def read_status() -> dict[str, dict[str, str]]:
    rows: dict[str, dict[str, str]] = {}
    path = ROOT / "verification/gate_status.tsv"
    if path.exists():
        for line in path.read_text().splitlines():
            name, result, seconds, command = line.split("\t", 3)
            if result == "PASS" and not (LOGS / f"{name}.log").exists():
                result = "FAIL"
            rows[name] = {"result": result, "seconds": seconds, "command": command}
    return rows


def log_text(name: str) -> str:
    path = LOGS / f"{name}.log"
    return re.sub(r"\x1b\[[0-9;]*m", "", path.read_text(errors="replace")) if path.exists() else ""


def find(pattern: str, text: str) -> str | None:
    matches = re.findall(pattern, text)
    return matches[-1] if matches else None


def main() -> None:
    status = read_status()
    backend = log_text("backend_tests")
    frontend = log_text("frontend_tests")
    safety = log_text("safety_suite")
    e2e = log_text("e2e_accessibility")
    smoke = log_text("smoke")
    lines = [
        "# Verification report",
        "",
        "Generated by `scripts/make_report.py` from captured logs. No result here was written by hand.",
        "",
        f"- **Generated:** {datetime.now(UTC).strftime('%Y-%m-%d %H:%M UTC')}",
        f"- **Host:** {platform.system()} {platform.release()} {platform.machine()}",
        f"- **Tools:** {version('docker', '--version')}; {version('docker', 'compose', 'version')}; "
        f"Node {version('node', '--version')}; {version('backend/.venv/bin/python', '--version')}",
        "",
        "## Gates",
        "",
        "| Gate | Requirement | Result | Time | Log |",
        "|---|---|---|---|---|",
    ]
    for name, requirement in GATES.items():
        row = status.get(name)
        if row:
            lines.append(
                f"| {name} | {requirement} | **{row['result']}** | {row['seconds']}s | "
                f"[log](verification/logs/{name}.log) |"
            )
        else:
            lines.append(f"| {name} | {requirement} | **NOT EXECUTED** | | |")
    lines += ["", "## Exact commands", ""]
    for name, row in status.items():
        lines.append(f"- `{name}`: `{row['command']}`")
    lines += ["", "## Measured results", ""]
    backend_passed = find(r"(\d+ passed[^\n]*)", backend)
    if backend_passed:
        lines.append(f"- **Backend tests:** {backend_passed.strip(' =')}")
    coverage = ROOT / "verification/coverage-backend.json"
    if coverage.exists():
        lines.append(f"- **Backend line coverage:** {json.loads(coverage.read_text())['totals']['percent_covered']:.1f}%")
    core = find(r"core modules: ([\d.]+%[^\n]*)", backend)
    if core:
        lines.append(f"- **Core module coverage (safety, matching, pricing):** {core}")
    safety_passed = find(r"(\d+ passed[^\n]*)", safety)
    if safety_passed:
        lines.append(f"- **Safety suite:** {safety_passed.strip(' =')}")
    frontend_tests = find(r"Tests\s+(\d+ passed[^\n]*)", frontend)
    if frontend_tests:
        lines.append(f"- **Frontend tests:** {frontend_tests}")
    summary_file = ROOT / "frontend/coverage/coverage-summary.json"
    if summary_file.exists():
        lines.append(f"- **Frontend line coverage:** {json.loads(summary_file.read_text())['total']['lines']['pct']}%")
    e2e_count = find(r"(\d+ passed[^\n]*)", e2e)
    if e2e_count:
        lines.append(f"- **End-to-end tests (desktop and mobile):** {e2e_count}")
    e2e_failed = find(r"(\d+ failed)", e2e)
    if e2e_failed:
        lines.append(f"- **End-to-end failures:** {e2e_failed}")
    smoke_line = find(r"(SMOKE PASS: \d+ checks)", smoke)
    if smoke_line:
        lines.append(f"- **Smoke:** {smoke_line}")
    stats = ROOT / "verification/perf/locust_stats.csv"
    if stats.exists():
        import csv

        lines += [
            "",
            "### Load test",
            "",
            "| Route | Requests | Failures | p50 ms | p95 ms | p99 ms | Requests/s |",
            "|---|---|---|---|---|---|---|",
        ]
        for row in csv.DictReader(stats.open()):
            lines.append(
                f"| {row['Name']} | {row['Request Count']} | {row['Failure Count']} | {row['50%']} | "
                f"{row['95%']} | {row['99%']} | {float(row['Requests/s']):.1f} |"
            )
        lines += ["", "Local Docker on one laptop, so client and server share the machine. Not a production capacity figure."]
    results = ROOT / "evaluation/results/results.json"
    if results.exists():
        data = json.loads(results.read_text())
        chosen = data["selected_engine"]
        test = data["engines"][chosen]["calibrated_test"]
        lines += [
            "",
            "### OCR evaluation headline (synthetic data only)",
            "",
            f"- **Selected engine:** {chosen}. Thresholds were chosen on the validation split.",
            f"- **Test split at those thresholds:** {test['suggested']} suggestions, {test['false_matches']} false matches, "
            f"95% upper bound on false-match rate {100 * (test['false_match_rate_upper_95'] or 0):.1f}%, "
            f"coverage of readable lines {100 * (test['coverage_of_identifiable_lines'] or 0):.1f}%.",
            "- **Limit:** synthetic handwriting is easier than real doctor handwriting. See docs/EVALUATION.md.",
        ]
    justification = ROOT / "verification/security/JUSTIFICATIONS.md"
    lines += ["", "## Security findings", ""]
    if justification.exists():
        lines.append(justification.read_text().strip())
    else:
        lines.append("See the `security` log. Findings fail the gate unless justified here.")
    lines += ["", "## Not executed here", "", "| Item | Reason | How to run it |", "|---|---|---|"]
    for name, (reason, how) in NOT_RUNNABLE.items():
        lines.append(f"| {name} | {reason} | `{how}` |" if how.startswith(("docker", "Set")) else f"| {name} | {reason} | {how} |")
    packaging = ROOT / "verification/package_check.md"
    if packaging.exists():
        lines += ["", "## Unzipped copy check", "", packaging.read_text().strip()]
    lines.append("")
    (ROOT / "VERIFICATION_REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote VERIFICATION_REPORT.md")


if __name__ == "__main__":
    main()
